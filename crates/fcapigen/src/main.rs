//! Generates `crates/fcapi/src/types.rs` from Firecracker's swagger spec at a release tag. `mise run generate` pins
//! the URL.

use std::{fs, path::PathBuf};

use anyhow::{Context as _, bail};
use clap::Parser;

#[derive(Parser)]
struct Args {
    /// URL of firecracker.yaml at a release tag
    #[arg(long)]
    spec: String,
    #[arg(long, default_value = "types.rs")]
    out: PathBuf,
}

fn main() -> anyhow::Result<()> {
    let args = Args::parse();
    let tag = release_tag(&args.spec)?;
    let spec = ureq::get(&args.spec).call().context("fetch the spec")?.body_mut().read_to_string().context("read the spec")?;
    let code = generate(&spec, tag)?;
    fs::write(&args.out, code).with_context(|| format!("write {}", args.out.display()))
}

/// The `vX.Y.Z` in a URL like `.../firecracker/v1.17.0/src/...`.
fn release_tag(url: &str) -> anyhow::Result<&str> {
    let tag = url.split('/').skip_while(|part| *part != "firecracker").nth(1).unwrap_or_default();
    let numbers: Vec<_> = tag.strip_prefix('v').unwrap_or_default().split('.').collect();
    if numbers.len() != 3 || numbers.iter().any(|n| n.is_empty() || !n.bytes().all(|b| b.is_ascii_digit())) {
        bail!("--spec has no /firecracker/vX.Y.Z/ release tag: {url}");
    }
    Ok(tag)
}

fn generate(spec: &str, tag: &str) -> anyhow::Result<String> {
    let swagger: serde_json::Value = serde_norway::from_str(spec).context("parse the swagger spec")?;
    // swagger 2 definitions are just JSON Schema, and #/definitions/ refs resolve the same way at a schema's root.
    let root = serde_json::json!({ "definitions": swagger["definitions"] });
    let schema: schemars::schema::RootSchema = serde_json::from_value(root).context("read the definitions as JSON Schema")?;
    let settings = typify::TypeSpaceSettings::default().with_struct_builder(false).with_derive("PartialEq".to_owned()).clone();
    let mut types = typify::TypeSpace::new(&settings);
    types.add_root_schema(schema).context("generate types")?;
    let file: syn::File = syn::parse2(types.to_stream()).context("parse the generated code")?;
    Ok(format!(
        "// Code generated by fcapigen from the firecracker {tag} swagger spec. DO NOT EDIT.\n\n\
         /// The release these types were generated from.\n\
         pub const FIRECRACKER_TAG: &str = {tag:?};\n\n{}",
        prettyplease::unparse(&file)
    ))
}

#[cfg(test)]
mod tests {
    use rstest::rstest;

    use super::*;

    #[test]
    fn spec_urls_name_a_release() {
        let url = "https://raw.githubusercontent.com/firecracker-microvm/firecracker/v1.17.0/src/firecracker/swagger/firecracker.yaml";
        assert_eq!(release_tag(url).unwrap(), "v1.17.0");
    }

    #[rstest]
    #[case::branch("https://raw.githubusercontent.com/firecracker-microvm/firecracker/main/src/firecracker/swagger/firecracker.yaml")]
    #[case::no_repo("https://example.com/firecracker.yaml")]
    #[case::partial_version(
        "https://raw.githubusercontent.com/firecracker-microvm/firecracker/v1.17/src/firecracker/swagger/firecracker.yaml"
    )]
    fn other_spec_urls_are_refused(#[case] url: &str) {
        assert!(release_tag(url).is_err());
    }

    #[test]
    fn definitions_become_types() {
        let spec = r"
definitions:
  Vsock:
    type: object
    required: [guest_cid, uds_path]
    properties:
      guest_cid: {type: integer, minimum: 3}
      uds_path: {type: string}
  Logger:
    type: object
    properties:
      level: {type: string, enum: [Error, Warning]}
";
        let code = generate(spec, "v1.2.3").unwrap();
        assert!(code.starts_with("// Code generated by fcapigen from the firecracker v1.2.3"));
        assert!(code.contains(r#"pub const FIRECRACKER_TAG: &str = "v1.2.3";"#));
        assert!(code.contains("pub struct Vsock"));
        assert!(code.contains("pub uds_path: ::std::string::String"));
        assert!(code.contains("pub enum LoggerLevel"));
    }
}
